export const palace = (p: number): Lines[] => {
	const base = [...TRI_LINES[TRI.indexOf(GONG[p])], ...TRI_LINES[TRI.indexOf(GONG[p])]];
	const out: Lines[] = [base];
	let cur = base;
	for (let k = 0; k < 5; k++) { cur = bian(cur, k); out.push(cur); }
	const you = bian(cur, 3); out.push(you);
	out.push([...base.slice(0, 3), ...you.slice(3)]);
	return out;
};
export const PALACES = GONG.map((_, p) => palace(p));

// 自检（仅在 node 环境下由 check 脚本调用）
export const selfCheck = () => {
	const errs: string[] = [];
	if (new Set(KW.map((g) => g.v)).size !== 64) errs.push('KW not 64 unique');
	for (let i = 0; i < 64; i += 2) {
		const a = KW[i].lines, b = KW[i + 1].lines;
		if (!same(zong(a), b) && !same(cuo(a), b)) errs.push(`pair ${i + 1} broken`);
	}
	const all = new Set(PALACES.flat().map((l) => toV(l)));
	if (all.size !== 64) errs.push('palaces not cover 64: ' + all.size);
	return errs;
};
